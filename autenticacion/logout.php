
<?php

/* ============================================================
   SISTEMA: TUTORLINK
   ARCHIVO: logout.php
   DESCRIPCIÓN: Cerrar sesión y regresar al inicio
   ============================================================ */


/* ============================================================
   1. INICIAR SESIÓN
   ============================================================ */

session_start();


/* ============================================================
   2. VACIAR LOS DATOS DE LA SESIÓN
   ============================================================ */

$_SESSION = [];


/* ============================================================
   3. ELIMINAR LA COOKIE DE SESIÓN
   ============================================================ */

if (ini_get("session.use_cookies")) {

    $datos = session_get_cookie_params();

    setcookie(
        session_name(),
        "",
        time() - 42000,
        $datos["path"],
        $datos["domain"],
        $datos["secure"],
        $datos["httponly"]
    );
}


/* ============================================================
   4. DESTRUIR LA SESIÓN
   ============================================================ */

session_destroy();


/* ============================================================
   5. REGRESAR AL INICIO DE SESIÓN
   ============================================================ */


header("Location: ../index.php");
exit;

?>